local Lang = require("kr2anki/lang")

describe("lang.normalize", function()
    it("maps tags, ISO 639-2 codes and names", function()
        assert.equal("ja", Lang.normalize("ja-JP"))
        assert.equal("ja", Lang.normalize("jpn"))
        assert.equal("ja", Lang.normalize("Japanese"))
        assert.equal("zh", Lang.normalize("zh_CN"))
        assert.equal("zh", Lang.normalize("zh-Hans"))
        assert.equal("zh", Lang.normalize("chi"))
        assert.equal("ko", Lang.normalize("kor"))
        assert.equal("en", Lang.normalize("en-US"))
        assert.equal("fr", Lang.normalize("fre"))
        assert.is_nil(Lang.normalize(""))
        assert.is_nil(Lang.normalize("und"))
        assert.is_nil(Lang.normalize(nil))
    end)
end)

describe("lang.detect", function()
    it("treats kana as Japanese whatever the book says", function()
        assert.equal("ja", (Lang.detect{ word = "打ち明ける", book_lang = "zh" }))
        assert.equal("ja", (Lang.detect{ word = "コーヒー" }))
    end)

    it("treats Hangul as Korean", function()
        assert.equal("ko", (Lang.detect{ word = "먹다", book_lang = "en" }))
    end)

    it("lets the book language decide Han-only words", function()
        assert.equal("ja", (Lang.detect{ word = "先生", book_lang = "ja" }))
        assert.equal("zh", (Lang.detect{ word = "先生", book_lang = "zh-CN" }))
        assert.equal("ja", (Lang.detect{ word = "犠牲", book_lang = "jpn" }))
    end)

    it("puts the per-book override before the book metadata", function()
        assert.equal("ja", (Lang.detect{ word = "打算", book_lang = "zh", book_override = "ja" }))
        assert.equal("zh", (Lang.detect{ word = "打算", book_lang = "ja", book_override = "zh" }))
    end)

    it("falls back to the dictionary language, then Chinese, for Han-only words", function()
        local code, reason = Lang.detect{ word = "打算", book_lang = "en", dict_lang = "ja" }
        assert.equal("ja", code)
        assert.equal("dictionary", reason)
        code, reason = Lang.detect{ word = "打算" }
        assert.equal("zh", code)
        assert.equal("han-default", reason)
    end)

    it("uses the book language for Latin words unless the book is CJK", function()
        assert.equal("fr", (Lang.detect{ word = "maison", book_lang = "fr" }))
        assert.equal("en", (Lang.detect{ word = "run", book_lang = "ja" }))
        assert.equal("de", (Lang.detect{ word = "Haus", book_lang = "ja", dict_lang = "de" }))
        assert.equal("en", (Lang.detect{ word = "run" }))
    end)
end)

describe("lang.deckName", function()
    it("fills the language name", function()
        assert.equal("Reading::Japanese", Lang.deckName("Reading::{Language}", "ja"))
        assert.equal("Lang::ko", Lang.deckName("Lang::{lang}", "ko"))
        assert.equal("Reading::English", Lang.deckName(nil, "en"))
        assert.equal("Reading::French", Lang.deckName(nil, "fr"))
    end)
end)
