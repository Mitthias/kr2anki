local T = require("testdb")

describe("store: saving", function()
    local store
    before_each(function() store = T.new() end)
    after_each(function() os.remove(store._test_path) end)

    it("creates an item with its first sense, sentence, lookups and book", function()
        local r = store:saveCapture(T.capture())
        assert.is_true(r.created)
        assert.equal(1, r.inbox)
        local it = store:getItem(r.item_id)
        assert.equal("打ち明ける", it.lemma)
        assert.equal("打ち明けない", it.surface)
        assert.equal("うちあける", it.reading)
        assert.equal("to confide (a secret); to reveal", it.definition)
        assert.equal(1, it.chosen_sense)
        assert.equal("Ichidan verb, transitive", it.pos)
        assert.equal("友達に悩みを打ち明けた。", it.dict_examples)
        assert.equal("inbox", it.status)
        assert.equal(2, #it.lookups)
        assert.equal("JMdict", it.lookups[1].dictionary)
        assert.equal("隠さずにすべて話す。", it.lookups[2].parsed.senses[1].text)
        assert.equal(1, #it.sentences)
        assert.equal("こころ", it.sentence.book.title)
        assert.equal(10, it.sentence.hl_start)
        assert.equal("3", it.sentence.page)
        assert.truthy(it.uid and #it.uid >= 8)
    end)

    it("adds a sentence instead of duplicating the same lemma and language", function()
        local r1 = store:saveCapture(T.capture())
        local r2 = store:saveCapture(T.capture({ surface = "打ち明けた",
            sentence = { text = "全部打ち明けた。", hl_start = 7, hl_end = 21 },
            book = { title = "坊っちゃん", authors = "夏目漱石", file_hash = "zzz" } }))
        assert.is_false(r2.created)
        assert.equal(r1.item_id, r2.item_id)
        local it = store:getItem(r1.item_id)
        assert.equal(2, it.lookup_count)
        assert.equal(2, #it.sentences)
        assert.equal(2, #it.books)
        assert.equal(2, #it.lookups, "same dictionaries are not stored twice")
        assert.equal(1, store:counts().inbox)
        -- other language: a separate item
        local r3 = store:saveCapture(T.capture({ language = "zh" }))
        assert.is_true(r3.created)
    end)

    it("undoes a fresh save completely", function()
        local r = store:saveCapture(T.capture())
        store:undoSave(r)
        assert.is_nil(store:getItem(r.item_id))
        assert.equal(0, store:counts().total)
    end)

    it("undoes an added sentence and restores the count", function()
        local r1 = store:saveCapture(T.capture())
        local r2 = store:saveCapture(T.capture({ sentence = { text = "second", hl_start = 1, hl_end = 6 } }))
        store:undoSave(r2)
        local it = store:getItem(r1.item_id)
        assert.equal(1, it.lookup_count)
        assert.equal(1, #it.sentences)
        assert.equal("本名は打ち明けない。", it.sentence.text)
    end)

    it("marks In Anki items for update when a sentence is added", function()
        local r = store:saveCapture(T.capture())
        store:setStatus({ r.item_id }, "ready")
        store:markExported(r.item_id, 1700000000123)
        local r2 = store:saveCapture(T.capture({ sentence = { text = "another", hl_start = 1, hl_end = 7 } }))
        assert.equal("anki", r2.status)
        local it = store:getItem(r.item_id)
        assert.equal(1, it.needs_update)
        assert.equal(1700000000123, it.anki_note_id)
        assert.equal(1, store:counts().updates)
    end)

    it("moves a Known item back to the Inbox only when asked", function()
        local r = store:saveCapture(T.capture())
        store:setStatus({ r.item_id }, "known")
        local r2 = store:saveCapture(T.capture())
        assert.equal("known", r2.status)
        local r3 = store:saveCapture(T.capture({ reactivate = true }))
        assert.equal("inbox", r3.status)
        store:undoSave(r3)
        assert.equal("known", store:getItem(r.item_id).status)
    end)

    it("does not store the same sentence twice", function()
        local r1 = store:saveCapture(T.capture())
        local r2 = store:saveCapture(T.capture())
        assert.is_true(r2.duplicate_sentence)
        local it = store:getItem(r1.item_id)
        assert.equal(1, #it.sentences)
        assert.equal(1, it.lookup_count)
        store:undoSave(r2)
        assert.equal(1, store:getItem(r1.item_id).lookup_count)
        assert.equal(1, #store:getItem(r1.item_id).sentences)
    end)

    it("saves without a definition", function()
        local r = store:saveCapture(T.capture({ lookups = {}, lemma = "珍語" }))
        local it = store:getItem(r.item_id)
        assert.is_nil(it.definition)
        assert.equal(0, #it.lookups)
        assert.equal("珍語", it.lemma)
    end)

    it("saves expressions keyed by their pattern", function()
        local r = store:saveCapture(T.capture({ type = "expression", surface = "なくてはならない", pattern = "なくてはならない", lookups = {} }))
        local it = store:getItem(r.item_id)
        assert.equal("expression", it.type)
        assert.equal("なくてはならない", it.pattern)
        store:update(r.item_id, { pattern = "〜なくてはならない", meaning = "must" })
        it = store:getItem(r.item_id)
        assert.equal("〜なくてはならない", it.lemma)
        assert.equal("must", it.meaning)
    end)
end)

describe("store: statuses", function()
    local store, ids
    before_each(function()
        store = T.new()
        ids = {}
        for i, w in ipairs({ "淋しい", "罪悪", "書生" }) do
            ids[i] = store:saveCapture(T.capture({ lemma = w, surface = w })).item_id
        end
        ids[4] = store:saveCapture(T.capture({ type = "expression", pattern = "〜なくては", surface = "なくては", lookups = {} })).item_id
    end)
    after_each(function() os.remove(store._test_path) end)

    it("follows the allowed transitions", function()
        local r = store:setStatus({ ids[1] }, "anki")
        assert.equal(0, r.changed)
        assert.equal(1, r.skipped_invalid)
        assert.equal(1, store:setStatus({ ids[1] }, "ready").changed)
        assert.equal(1, store:setStatus({ ids[1] }, "anki").changed)
        assert.equal(0, store:setStatus({ ids[1] }, "inbox").changed)
        assert.equal(1, store:setStatus({ ids[1] }, "known").changed)
        assert.equal(1, store:setStatus({ ids[1] }, "inbox").changed)
        assert.equal(1, store:setStatus({ ids[2] }, "discarded").changed)
        assert.equal(0, store:setStatus({ ids[2] }, "ready").changed)
    end)

    it("skips expressions without a meaning unless allowed", function()
        local r = store:setStatus(ids, "ready", { allow_empty_meaning = false })
        assert.equal(3, r.changed)
        assert.equal(1, r.skipped_meaning)
        r = store:setStatus({ ids[4] }, "ready", { allow_empty_meaning = true })
        assert.equal(1, r.changed)
    end)

    it("counts, lists and searches", function()
        store:setStatus({ ids[1] }, "ready")
        local c = store:counts()
        assert.equal(3, c.inbox)
        assert.equal(1, c.ready)
        assert.equal(4, store:count({ language = "ja" }))
        assert.equal(1, store:count({ statuses = { ready = true } }))
        assert.equal(1, store:count({ type = "expression" }))
        assert.equal(1, store:count({ search = "なくては" }))
        assert.equal(3, store:count({ search = "うちあける" }), "reading matches (the expression has none)")
        assert.equal(3, store:count({ search = "confide" }), "meaning matches")
        local by = store:inboxByLanguage()
        assert.equal("ja", by[1].language)
        assert.equal(2, by[1].words)
        assert.equal(1, by[1].expressions)
        local books = store:booksFor({ language = "ja" })
        assert.equal(1, #books)
        assert.equal("こころ", books[1].title)
        assert.equal(4, books[1].n)
        assert.equal(3, #store:reviewQueue())
        assert.equal(ids[4], store:reviewQueue()[1], "newest first")
    end)

    it("sorts A–Z by reading", function()
        store:update(ids[1], { reading = "さびしい" })
        store:update(ids[2], { reading = "ざいあく" })
        store:update(ids[3], { reading = "しょせい" })
        local list = store:query({ type = "word" }, "az")
        assert.equal("淋しい", list[1].lemma)
        assert.equal("罪悪", list[2].lemma)
        assert.equal("書生", list[3].lemma)
    end)

    it("deletes items and their children", function()
        store:delete({ ids[1], ids[2] })
        assert.equal(2, store:counts().total)
        assert.is_nil(store:getItem(ids[1]))
    end)

    it("chooses a sense from another lookup", function()
        local it = store:getItem(ids[1])
        store:chooseSense(ids[1], it.lookups[2].id, 1)
        it = store:getItem(ids[1])
        assert.equal("隠さずにすべて話す。", it.definition)
        assert.equal("大辞林", it.dictionary)
        assert.equal(it.lookups[2].id, it.chosen_lookup_id)
    end)

    it("converts between word and expression", function()
        store:setType(ids[1], "expression")
        local it = store:getItem(ids[1])
        assert.equal("expression", it.type)
        assert.equal("淋しい", it.pattern)
        store:setType(ids[1], "word")
        assert.equal("word", store:getItem(ids[1]).type)
    end)
end)

describe("store: schema", function()
    it("records a schema version", function()
        local store = T.new()
        assert.equal(1, store:schemaVersion())
        -- reopening does not fail or duplicate the version row
        local Store = require("kr2anki/db")
        local again = Store.new(store._test_path, { json = require("json") })
        assert.equal(1, again:schemaVersion())
        os.remove(store._test_path)
    end)
end)
