local R = require("kr2anki/ruby")

describe("furigana alignment", function()
    it("splits the reading per kanji run", function()
        assert.equal("打[う]ち 明[あ]ける", (R.furigana("打ち明ける", "うちあける")))
        assert.equal("犠牲[ぎせい]", (R.furigana("犠牲", "ぎせい")))
        assert.equal("淋[さび]しい", (R.furigana("淋しい", "さびしい")))
        assert.equal("向上心[こうじょうしん]", (R.furigana("向上心", "こうじょうしん")))
        assert.equal("若々[わかわか]しい", (R.furigana("若々しい", "わかわかしい")))
        assert.equal("食[た]べ 物[もの]", (R.furigana("食べ物", "たべもの")))
        assert.equal("お 茶[ちゃ]", (R.furigana("お茶", "おちゃ")))
    end)

    it("matches katakana in the reading or the word", function()
        assert.equal("打[ウ]ち 明[ア]ける", (R.furigana("打ち明ける", "ウチアケル")))
        assert.equal("消[け]しゴム", (R.furigana("消しゴム", "けしごむ")))
    end)

    it("falls back to the whole word when the kana do not line up", function()
        local ruby, fallback = R.furigana("今日", "きょう")
        assert.equal("今日[きょう]", ruby)
        assert.is_false(fallback)
        ruby = R.furigana("大人しい", "おとなしい")
        assert.equal("大人[おとな]しい", ruby)
        ruby, fallback = R.furigana("打ち明ける", "たべる")
        assert.equal("打ち明ける[たべる]", ruby)
        assert.is_true(fallback)
    end)

    it("returns nil for kana-only words or a missing reading", function()
        assert.is_nil(R.furigana("なる", "なる"))
        assert.is_nil(R.furigana("成る", ""))
    end)
end)

describe("pinyin", function()
    it("converts tone numbers to marks", function()
        assert.equal("dǎ suàn", R.numberedToMarks("da3 suan4"))
        assert.equal("lǜ", R.numberedToMarks("lu:4"))
        assert.equal("nǚ", R.numberedToMarks("nv3"))
        assert.equal("xiǎo", R.numberedToMarks("xiao3"))
        assert.equal("duō", R.numberedToMarks("duo1"))
        assert.equal("liú", R.numberedToMarks("liu2"))
        assert.equal("guì", R.numberedToMarks("gui4"))
        assert.equal("ma", R.numberedToMarks("ma5"))
        assert.equal("Běi jīng", R.numberedToMarks("Bei3 jing1"))
    end)

    it("splits joined syllables", function()
        assert.same({ "dǎ", "suàn" }, R.splitPinyin("dǎsuàn"))
        assert.same({ "Xī", "ān" }, R.splitPinyin("Xī'ān"))
        assert.same({ "zhōng", "guó", "rén" }, R.splitPinyin("zhong1guo2ren2"))
    end)

    it("aligns one syllable per character", function()
        assert.equal("打[dǎ] 算[suàn]", (R.pinyin("打算", "da3 suan4")))
        assert.equal("打[dǎ] 算[suàn]", (R.pinyin("打算", "dǎsuàn")))
        assert.equal("中[zhōng] 国[guó] 人[rén]", (R.pinyin("中国人", "zhōng guó rén")))
    end)

    it("falls back to the whole word when counts differ", function()
        local ruby, fallback = R.pinyin("卡拉OK", "ka3 la1 ou1 kei4")
        assert.equal("卡拉OK[kǎ lā ōu kèi]", ruby)
        assert.is_true(fallback)
        local _, fb = R.pinyin("一会儿", "yī huìr")
        assert.is_true(fb)
    end)
end)

describe("Korean romanization", function()
    it("romanizes with liaison", function()
        assert.equal("meokda", R.romanizeKorean("먹다"))
        assert.equal("meogeo", R.romanizeKorean("먹어"))
        assert.equal("hangugeo", R.romanizeKorean("한국어"))
        assert.equal("seoul", R.romanizeKorean("서울"))
        assert.equal("hallim", R.romanizeKorean("할림"))
    end)
end)
